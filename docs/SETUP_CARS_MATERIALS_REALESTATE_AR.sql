create table if not exists public.car_listings (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  category text not null,
  price numeric,
  phone text not null,
  governorate text,
  area text not null,
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.material_listings (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  category text not null,
  price numeric not null,
  phone text not null,
  governorate text,
  area text not null,
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.real_estate_listings (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  category text not null,
  price numeric not null,
  phone text not null,
  governorate text,
  area text not null,
  description text,
  created_at timestamptz not null default now()
);

alter table public.car_listings enable row level security;
alter table public.material_listings enable row level security;
alter table public.real_estate_listings enable row level security;

grant select on public.car_listings, public.material_listings, public.real_estate_listings to anon, authenticated;
grant insert, update, delete on public.car_listings, public.material_listings, public.real_estate_listings to authenticated;
grant usage, select on all sequences in schema public to authenticated;

drop policy if exists "Anyone can view car listings" on public.car_listings;
create policy "Anyone can view car listings" on public.car_listings for select to anon, authenticated using (true);
drop policy if exists "Users create own car listings" on public.car_listings;
create policy "Users create own car listings" on public.car_listings for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "Users update own car listings" on public.car_listings;
create policy "Users update own car listings" on public.car_listings for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
drop policy if exists "Users delete own car listings" on public.car_listings;
create policy "Users delete own car listings" on public.car_listings for delete to authenticated using (user_id = auth.uid());

